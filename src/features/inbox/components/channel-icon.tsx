export function ChannelIcon({
  channel,
  className,
}: {
  channel: ChannelId | "all";
  className?: string;
}) {
  switch (channel) {
    case "slack":
      return <SlackIcon className={cn("size-3.5 shrink-0", className)} />;
    case "whatsapp":
      return <WhatsAppIcon className={cn("size-3.5 shrink-0", className)} />;
    case "email":
      return <Mail className={cn("size-3.5 shrink-0", className)} strokeWidth={2.2} />;
    case "messenger":
      return <MessengerIcon className={cn("size-3.5 shrink-0", className)} />;
    case "telegram":
      return <TelegramIcon className={cn("size-3.5 shrink-0", className)} />;
    case "instagram":
      return <InstagramIcon className={cn("size-3.5 shrink-0", className)} />;
    case "discord":
      return <DiscordIcon className={cn("size-3.5 shrink-0", className)} />;
    case "gmail":
      return <GmailIcon className={cn("size-3.5 shrink-0", className)} />;
    case "website":
      return <WebsiteIcon className={cn("size-3.5 shrink-0", className)} />;
    default:
      return null;
  }
}
